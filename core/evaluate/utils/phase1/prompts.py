"""
Phase 1 评估提示词定义

包含专业度评估和共情度评估的 System Prompt 和 User Prompt
"""

from typing import List, Dict, Any


def format_scale_text(scale_items: List[Dict[str, Any]], scale_type: str = "empathy") -> str:
    """将量表格式化为文本
    
    Args:
        scale_items: 量表条目列表
        scale_type: 量表类型，"empathy" 或 "profession"
        
    Returns:
        格式化后的量表文本
    """
    lines = []
    
    if scale_type == "empathy":
        # 共情量表：等级制
        for item in scale_items:
            level = item.get('level', '')
            description = item.get('description', '')
            
            lines.append(f"【等级 {level}】")
            lines.append(f"定义: {description}")
            
            # 添加 checklist
            checklist = item.get("checklist", [])
            if checklist:
                lines.append("评估要点:")
                for c in checklist:
                    lines.append(f"  - {c}")
            
            # 添加 indicators
            indicators = item.get("indicators", [])
            if indicators:
                lines.append("表现指标:")
                for i in indicators:
                    lines.append(f"  - {i}")
            
            # 添加 note（如果有）
            note = item.get("note", "")
            if note:
                lines.append(f"注: {note}")
            
            lines.append("")  # 空行分隔
    
    elif scale_type == "profession":
        # 专业度量表：题目制
        for item in scale_items:
            item_id = item.get('id', '')
            question = item.get('question', '')
            definition = item.get('definition', '')
            scores = item.get('scores', {})
            focus = item.get('focus', [])
            example = item.get('example', {})
            
            lines.append(f"【题目 {item_id}】")
            lines.append(f"问题: {question}")
            lines.append(f"定义: {definition}")
            
            # 添加评分标准
            if scores:
                lines.append("评分标准:")
                for score, desc in scores.items():
                    lines.append(f"  {score}分: {desc}")
            
            # 添加考察要点
            if focus:
                lines.append("考察要点:")
                for f in focus:
                    lines.append(f"  - {f}")
            
            # 添加示例
            if example:
                lines.append("示例:")
                for score, text in example.items():
                    lines.append(f"  {score}分: {text}")
            
            lines.append("")  # 空行分隔
    
    return "\n".join(lines).strip()


